#List of fruits
fruits = ["apple", "banana", "mango", "orange"]

#Accessing the first and the last fruit of the list using index
print( fruits[0])  
print( fruits[3])  

#Adding a new fruit to the list using the append() method
fruits.append("grape")  
print( fruits)  

#Removing a fruit from the list using the remove() method
fruits.remove("banana")
print( fruits)

#printing the number of fruits in the list using the len() function
print( len(fruits))

